tab_predict, tab_performance, tab_fairness = st.tabs(['🔍 Customer prediction', '📊 Model performance', '⚖️ Fairness audit'])
with tab_predict:
    st.subheader('Select an existing test customer')
    st.write('Select a saved test row. Only its features go into the model; the actual label is revealed afterward for comparison.')
    pos = int(index) - 1
    row_id = X.iloc[pos]['row_id']
    st.caption(f'Original row_id: {row_id} • Encoded feature count: {features.shape[1]}')
    if st.checkbox('Show encoded model inputs'):
        st.dataframe(features.iloc[[pos]].T.rename(columns={pos: 'Value'}), use_container_width=True)
    if st.button('Predict default risk', type='primary', use_container_width=True):
        probability = float(model.predict_proba(features.iloc[[pos]])[0, 1])
        predicted = int(probability >= CONFIG[choice]['threshold'])
        actual = int(saved.iloc[pos]['y_true'])
        # Reproduce the archived prediction as a consistency check.
        archived_probability = float(saved.iloc[pos]['probability'])
        archived_prediction = int(saved.iloc[pos]['y_pred'])
        if not np.isclose(probability, archived_probability, rtol=1e-5, atol=1e-6) or predicted != archived_prediction:
            st.error('Live prediction differs from archived evaluation. Check model and feature compatibility.')
            st.stop()
        a, b, c = st.columns(3)
        a.metric('Estimated default probability', f'{probability:.2%}')
        b.metric('Predicted outcome', 'Default (1)' if predicted else 'No Default (0)')
        c.metric('Actual test label', 'Default (1)' if actual else 'No Default (0)')
        if predicted == actual:
            st.success('Prediction matches the actual label for this saved test example.')
        else:
            st.warning('Prediction does not match the actual label for this saved test example.')
        st.caption(f"Decision: predict default when probability ≥ {CONFIG[choice]['threshold']:.2f}. This threshold was fixed during development.")

with tab_performance:
    st.subheader('Locked original-split test evaluation')
    cols = st.columns(6)
    for col, (name, key) in zip(cols, [('Accuracy','accuracy'),('Precision','precision'),('Recall','recall'),('F1','f1'),('ROC-AUC','roc_auc'),('Avg. precision','average_precision')]):
        col.metric(name, f"{metrics[key]:.4f}")
    st.write(f"**Test rows:** {metrics['test_rows']:,}  |  **Model:** {metrics['model']}  |  **Threshold:** {metrics['threshold']}")
    cm = pd.DataFrame([[metrics['tn'], metrics['fp']], [metrics['fn'], metrics['tp']]],
                      index=['Actual: No default', 'Actual: Default'],
                      columns=['Predicted: No default', 'Predicted: Default'])
    st.markdown('**Confusion matrix**')
    st.dataframe(cm, use_container_width=True)
    for title, filename in [('ROC curve', 'roc_curve.png'), ('Precision–recall curve', 'precision_recall_curve.png'), ('Confusion matrix plot', 'confusion_matrix.png')]:
        path = REPORTS / choice / filename
        if path.is_file():
            with st.expander(title):
                st.image(str(path), use_container_width=True)
    st.caption('These are the already recorded results; this page does not recalculate or retune the evaluation.')

with tab_fairness:
    st.subheader('Saved group-level fairness results')
    if not fairness:
        st.warning('No fairness CSV files found.')
    else:
        attribute = st.selectbox('Sensitive attribute', list(fairness), format_func=lambda s: s.replace('_', ' ').title())
        table = fairness[attribute].copy()
        st.dataframe(table, use_container_width=True, hide_index=True)
        if 'predicted_default_rate' in table:
            st.bar_chart(table.set_index('group')['predicted_default_rate'])
        if attribute == 'foreign_worker' and choice == 'german':
            st.warning('The non-foreign-worker group contains very few test examples; estimates are unstable.')
    st.caption('Group disparities are descriptive, not proof of discrimination. Predicted default is not an observed credit denial.')

st.divider()
