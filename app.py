"""Local Streamlit demo for the locked credit-default models.

Run from PAI_PROJECT root: python -m streamlit run app.py
Requires existing original-split evaluation outputs. Does not train or tune.
"""
from pathlib import Path
import json

import joblib
import numpy as np
import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parent
REPORTS = ROOT / 'reports' / 'final_test_evaluation_original_splits'
PROCESSED = ROOT / 'data' / 'processed'
CONFIG = {
    'german': {'title': 'German Credit', 'model': 'Logistic Regression', 'threshold': 0.40, 'n': 151},
    'taiwan': {'title': 'Taiwan Credit Card Default', 'model': 'Random Forest', 'threshold': 0.55, 'n': 4496},
}

st.set_page_config(page_title='Credit Default Prediction', page_icon='🏦', layout='wide')
st.title('🏦 Fairness-Aware Credit Default Prediction')
st.caption('Offline laptop demonstration • Locked trained models • Original held-out test examples')
st.info('This application predicts default risk, not an actual loan approval or denial. It is an educational research demo.')

@st.cache_resource
def get_model(dataset):
    path = REPORTS / dataset / 'model.joblib'
    if not path.is_file():
        raise FileNotFoundError(f'Missing trained model: {path}')
    return joblib.load(path)  # Load only models generated by your own trusted project.

@st.cache_data
def get_data(dataset):
    folder = PROCESSED / dataset
    report = REPORTS / dataset
    for path in (folder / 'X_test.csv', folder / 'y_test.csv', report / 'metrics.json', report / 'predictions.csv'):
        if not path.is_file():
            raise FileNotFoundError(f'Missing required file: {path}')
    X = pd.read_csv(folder / 'X_test.csv')
    y = pd.read_csv(folder / 'y_test.csv')
    saved = pd.read_csv(report / 'predictions.csv')
    metrics = json.loads((report / 'metrics.json').read_text(encoding='utf-8'))
    if not all('row_id' in df.columns for df in (X, y, saved)):
        raise ValueError('row_id column is required in X_test, y_test, and predictions')
    if X.row_id.duplicated().any() or y.row_id.duplicated().any() or saved.row_id.duplicated().any():
        raise ValueError('Duplicate row_id detected')
    if not (X.row_id.astype(str).tolist() == y.row_id.astype(str).tolist() == saved.row_id.astype(str).tolist()):
        raise ValueError('Saved test rows are not aligned. Do not proceed.')
    target_cols = [c for c in y.columns if c != 'row_id']
    if len(target_cols) != 1:
        raise ValueError(f'Expected one target column; got {target_cols}')
    if not np.array_equal(y[target_cols[0]].to_numpy(dtype=int), saved.y_true.to_numpy(dtype=int)):
        raise ValueError('Saved labels do not match original test labels')
    features = X.drop(columns=['row_id'])
    if len(features) != CONFIG[dataset]['n'] or int(metrics['test_rows']) != len(features):
        raise ValueError('Test row count does not match locked evaluation')
    if metrics['model'] != CONFIG[dataset]['model'] or not np.isclose(metrics['threshold'], CONFIG[dataset]['threshold']):
        raise ValueError('Saved evaluation configuration differs from locked model')
    if not all(pd.api.types.is_numeric_dtype(dt) for dt in features.dtypes):
        raise ValueError('Test features must be numeric')
    if not np.isfinite(features.to_numpy(dtype=float)).all():
        raise ValueError('Non-finite test features')
    fairness = {}
    for attribute in ('age_group', 'sex', 'foreign_worker'):
        path = report / f'fairness_{attribute}.csv'
        if path.is_file():
            fairness[attribute] = pd.read_csv(path)
    return X, features, saved, metrics, fairness

choice = st.sidebar.selectbox('Choose dataset', ['german', 'taiwan'], format_func=lambda d: CONFIG[d]['title'])
st.sidebar.markdown('**Model:** ' + CONFIG[choice]['model'])
st.sidebar.markdown(f"**Locked threshold:** {CONFIG[choice]['threshold']:.2f}")
st.sidebar.caption('Predictions use saved, training-fitted encoded test features. No training occurs in this app.')

try:
    X, features, saved, metrics, fairness = get_data(choice)
    model = get_model(choice)
    if getattr(model, 'n_features_in_', features.shape[1]) != features.shape[1]:
        raise ValueError('Model and test feature dimensions do not match')
    if hasattr(model, 'feature_names_in_') and list(model.feature_names_in_) != list(features.columns):
        raise ValueError('Feature order does not match the trained model')
except (FileNotFoundError, ValueError, KeyError, OSError) as exc:
    st.error(str(exc))
    st.code('python src/final_test_evaluation_fixed.py --dataset german\npython src/final_test_evaluation_fixed.py --dataset taiwan', language='powershell')
    st.stop()

tab_predict, tab_performance, tab_fairness = st.tabs(['🔍 Customer prediction', '📊 Model performance', '⚖️ Fairness audit'])
with tab_predict:
    st.subheader('Select an existing test customer')
    st.write('Select a saved test row. Only its features go into the model; the actual label is revealed afterward for comparison.')
    index = st.number_input('Test customer number (1-based)', min_value=1, max_value=len(X), value=1, step=1)
    pos = int(index) - 1
    row_id = X.iloc[pos]['row_id']
    st.caption(f'Original row_id: {row_id} • Encoded feature count: {features.shape[1]}')
    
